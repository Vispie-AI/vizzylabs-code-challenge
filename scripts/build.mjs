import { readFile, mkdir, writeFile, rename } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const plugin = new URL('../plugins/workbench/', import.meta.url);
export async function build(release = 'one') {
  if (!['one', 'two'].includes(release)) throw new Error('Unknown workspace release');
  const source = await readFile(new URL('src/client.js', plugin), 'utf8');
  await mkdir(new URL('lib/', plugin), { recursive: true });
  const file = new URL('lib/client.js', plugin);
  const temporary = new URL('lib/client.js.tmp', plugin);
  const content = `// Generated by scripts/build.mjs from src/client.js.\nwindow.__ModuleLoader__.load({\n  id: '@lantern/workbench',\n  factory: (require) => {\n    var module = { exports: {} };\n    var exports = module.exports;\n    var WORKBENCH_RELEASE = ${JSON.stringify(release)};\n${source}\n    return module.exports;\n  }\n});\n`;
  if (await readFile(file, 'utf8').catch(() => '') === content) return;
  await writeFile(temporary, content);
  await rename(temporary, file);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const patch = await readFile(new URL('../.dsh-home/profiles/web/cordis.patch.yml', import.meta.url), 'utf8').catch(() => '');
  await build(/release: (one|two)/.exec(patch)?.[1] || 'one');
}
