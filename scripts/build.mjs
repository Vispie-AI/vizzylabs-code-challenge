import { readFile, mkdir, writeFile, rename } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
async function output(file, content) {
  if (await readFile(file, 'utf8').catch(() => '') === content) return;
  await mkdir(new URL('./', file), { recursive: true });
  const temporary = new URL(file.href + '.tmp');
  await writeFile(temporary, content);
  await rename(temporary, file);
}
export async function build() {
  for (const plugin of ['workbench', 'navigation', 'editor', 'preview']) {
    const source = await readFile(new URL(`plugins/${plugin}/src/client.js`, root), 'utf8');
    await output(new URL(`plugins/${plugin}/lib/client.js`, root), `// Generated by scripts/build.mjs.\nwindow.__ModuleLoader__.load({\n  id: '@lantern/${plugin}',\n  factory: (require) => {\n    var module = { exports: {} };\n    var exports = module.exports;\n${source}\n    return module.exports;\n  }\n});\n`);
    if (plugin === 'workbench') continue;
    const view = await readFile(new URL(`plugins/${plugin}/src/view.js`, root), 'utf8');
    for (const release of ['one', 'two']) {
      const css = await readFile(new URL(`plugins/${plugin}/releases/${release}.css`, root), 'utf8');
      await output(new URL(`plugins/${plugin}/lib/${release}.mjs`, root), `// Generated by scripts/build.mjs.\nconst RELEASE = ${JSON.stringify(release)};\nconst STYLE = ${JSON.stringify(css)};\n${view}`);
    }
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await build();
